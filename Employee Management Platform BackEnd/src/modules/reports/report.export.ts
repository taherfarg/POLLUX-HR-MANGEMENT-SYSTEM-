export async function toXlsx(report: ReportDocument): Promise<Buffer> {
  const workbook = new ExcelJS.Workbook();
  workbook.creator = 'Pollux HR';
  workbook.created = report.generatedAt;

  const sheet = workbook.addWorksheet(report.title.slice(0, 31).replace(/[\\/?*[\]:]/g, ' '), {
    views: [{ state: 'frozen', ySplit: 1 }],
  });
  sheet.columns = report.columns.map((column) => ({
    header: column.label,
    key: column.key,
    width: Math.max(10, Math.min(40, (column.width ?? 1) * 12)),
    style:
      column.type === 'money'
        ? { numFmt: '#,##0.00' }
        : column.type === 'number'
          ? { numFmt: '0.##' }
          : {},
  }));
  const header = sheet.getRow(1);
  header.font = { bold: true, color: { argb: 'FFFFFFFF' } };
  header.fill = { type: 'pattern', pattern: 'solid', fgColor: { argb: 'FF1F2A44' } };

  for (const row of report.rows) {
    const values: Record<string, string | number | null> = {};
    for (const column of report.columns) {
      const value = row[column.key] ?? null;
      // Cells are typed as numbers only where the column is numeric; the
      // Decimal string is parsed at the very edge, for display in Excel.
      values[column.key] =
        value !== null && (column.type === 'money' || column.type === 'number' || column.type === 'minutes') && value !== ''
          ? Number(value)
          : value;
    }
    sheet.addRow(values);
  }
  sheet.autoFilter = { from: { row: 1, column: 1 }, to: { row: 1, column: report.columns.length } };

  const info = workbook.addWorksheet('Report info');
  info.columns = [
    { header: 'Field', key: 'field', width: 22 },
    { header: 'Value', key: 'value', width: 60 },
  ];
  info.getRow(1).font = { bold: true };
  info.addRows([
    { field: 'Report', value: report.title },
    { field: 'Filters', value: report.subtitle },
    { field: 'Company', value: report.companyName },
    { field: 'Generated at', value: report.generatedAt.toISOString() },
    { field: 'Generated by', value: report.generatedBy },
    ...report.summary.map((entry) => ({ field: entry.label, value: entry.value })),
  ]);

  return Buffer.from(await workbook.xlsx.writeBuffer());
}

