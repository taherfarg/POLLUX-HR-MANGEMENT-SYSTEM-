import ExcelJS from 'exceljs';
import PDFDocument from 'pdfkit';

/**
 * Turns a report - columns plus rows of plain values - into CSV, Excel or PDF.
 *
 * Money arrives as a Decimal-formatted string ("12345.60") and is written as
 * such: no float ever touches an amount on its way into a file.
 */

export type ColumnType = 'text' | 'number' | 'money' | 'date' | 'minutes';

export interface ReportColumn {
  key: string;
  label: string;
  type?: ColumnType;
  /** Relative width in the PDF layout. */
  width?: number;
}

export type CellValue = string | number | null;
export type ReportRow = Record<string, CellValue>;

export interface ReportDocument {
  title: string;
  subtitle: string;
  columns: ReportColumn[];
  rows: ReportRow[];
  /** Label/value pairs shown under the table (totals). */
  summary: { label: string; value: string }[];
  generatedAt: Date;
  generatedBy: string;
  companyName: string;
}

// ---------------------------------------------------------------------------
// CSV
// ---------------------------------------------------------------------------

/**
 * A text cell a spreadsheet would read as a formula (=, +, -, @, tab, CR) is
 * prefixed with an apostrophe, so an employee named "=HYPERLINK(...)" cannot
 * run anything on the machine of whoever opens the export. Numeric cells are
 * written as they are - a negative amount is data, not a formula.
 */
export function neutraliseFormula(value: string): string {
  return /^[=+\-@\t\r]/.test(value) ? `'${value}` : value;
}

function csvCell(value: CellValue, type: ColumnType): string {
  if (value === null || value === undefined) return '';
  const text = typeof value === 'number' || type === 'money' || type === 'number' || type === 'minutes'
    ? String(value)
    : neutraliseFormula(String(value));
  return /[",\r\n]/.test(text) ? `"${text.replace(/"/g, '""')}"` : text;
}

export function toCsv(report: ReportDocument): Buffer {
  const lines = [
    report.columns.map((column) => csvCell(column.label, 'text')).join(','),
    ...report.rows.map((row) => report.columns.map((column) => csvCell(row[column.key] ?? null, column.type ?? 'text')).join(',')),
  ];
  // The byte-order mark makes Excel open UTF-8 (Arabic names) correctly.
  return Buffer.from(`﻿${lines.join('\r\n')}\r\n`, 'utf8');
}

